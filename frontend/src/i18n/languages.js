/**
 * Translate a key into the target language with fallback across 22+ Indic languages
 */
export function t(key, lang = 'hi') {
  if (CLINICAL_I18N[key]) {
    const entry = CLINICAL_I18N[key];
    if (entry[lang]) return entry[lang];
    if (lang === 'en') return entry['en'] || entry['hi'] || key;

    // Dialect & regional script bridge for Eighth Schedule Indian languages
    if (['as', 'mni'].includes(lang)) {
      if (entry['as']) return entry['as'];
      if (entry['bn']) return entry['bn'];
    }
    if (['mai', 'doi', 'ne', 'sa', 'kok'].includes(lang)) {
      if (entry['hi']) return entry['hi'];
    }
    if (['sd', 'ks'].includes(lang)) {
      if (entry['ur']) return entry['ur'];
      if (entry['hi']) return entry['hi'];
    }
    if (['brx', 'sat'].includes(lang)) {
      if (entry['as']) return entry['as'];
      if (entry['hi']) return entry['hi'];
    }

    if (entry['hi']) return entry['hi'];
    if (entry['en']) return entry['en'];
  }
  return key;
}

/**
 * Speak text localized using browser SpeechSynthesis in the chosen regional Indian language
 */
export function speakLocalized(text, lang = 'hi', rate = 0.95) {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) return;
  try {
    window.speechSynthesis.cancel();
    const utterance = new SpeechSynthesisUtterance(text);
    const langObj = INDIAN_LANGUAGES.find(l => l.code === lang);
    utterance.lang = langObj?.speechVoiceCode || 'hi-IN';
    utterance.rate = rate;
    window.speechSynthesis.speak(utterance);
  } catch (err) {
    console.warn('Speech synthesis note:', err);
  }
}
